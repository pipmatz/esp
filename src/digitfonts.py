# ---------------------------------------------------------------- STENCIL
# ROUND with the waist cut out — every glyph is severed across the middle.

def _stencil(src):
    g = {}
    for k, rows in src.glyphs.items():
        r = list(rows)
        r[4] = "." * src.w
        g[k] = tuple(r)
    return BmpFont(g, src.w, src.h, src.adv)


STENCIL = _stencil(ROUND)


