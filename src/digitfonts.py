# digitfonts.py — alternative digit faces for the big seconds display.
#
# Each font is a bitmap (rows of '#' / '.') plus a renderer that scales it by
# an integer factor. SEG7 and LCD are procedural instead of bitmaps.
#
# All are full-stroke (no dithering, no dots) — the dotted look is gone.

import gfx


class BmpFont:
    def __init__(self, glyphs, w, h, adv):
        self.glyphs = glyphs
        self.w = w
        self.h = h
        self.adv = adv

    def width(self, s, scale):
        return len(s) * self.adv * scale - scale

    def draw(self, cv, s, x, y, scale, c):
        cx = x
        for i in range(len(s)):
            g = self.glyphs.get(s[i])
            if g is not None:
                for ry in range(self.h):
                    row = g[ry]
                    for rx in range(self.w):
                        if row[rx] == "#":
                            cv.fill_rect(cx + rx * scale, y + ry * scale,
                                         scale, scale, c)
            cx += self.adv * scale


