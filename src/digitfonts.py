# ---------------------------------------------------------------- SEG7 / LCD
# Procedural seven-segment. LCD is the same geometry with hairline segments.

class Seg7Font:
    def __init__(self, w=6, h=9, t=2, adv=7):
        self.w = w
        self.h = h
        self.t = t
        self.adv = adv

    def width(self, s, scale):
        return len(s) * self.adv * scale - scale

    def draw(self, cv, s, x, y, scale, c):
        cx = x
        for i in range(len(s)):
            ch = s[i]
            if ch == ":":
                gfx.seg7(cv, ":", cx, y, self.w * scale, self.h * scale,
                         self.t * scale, c, colon=True)
            else:
                gfx.seg7(cv, ch, cx, y, self.w * scale, self.h * scale,
                         self.t * scale, c)
            cx += self.adv * scale


SEG7 = Seg7Font(6, 9, 2, 7)
LCD = Seg7Font(6, 9, 1, 7)


