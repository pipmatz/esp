def blit(cv, rows, x, y, scale=1, c=0):
    for ry in range(len(rows)):
        row = rows[ry]
        for rx in range(len(row)):
            if row[rx] == "#":
                cv.fill_rect(x + rx * scale, y + ry * scale, scale, scale, c)


def size(rows, scale=1):
    return len(rows[0]) * scale, len(rows) * scale
